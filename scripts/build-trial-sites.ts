/**
 * Where each trial in OnCo is recruiting, read from the ClinicalTrials.gov capture the trial records already cite.
 *
 *   npx tsx scripts/build-trial-sites.ts                        # reads .cache/trial-participation
 *   npx tsx scripts/build-trial-sites.ts --cache=/path/to/.cache/trial-participation
 *
 * No network. scripts/fetch-trial-participation.ts keeps every study it captured in .cache/trial-participation and
 * writes the fields a page can show into src/data/trial-participation.ts, with the SHA-256 of each study. The site
 * lists stayed out of that file because they are a quarter of a 390 MB capture. This reads the same snapshots and
 * keeps only what "Trials recruiting here" needs: for each study, the sites whose own status is RECRUITING, counted
 * by country and city, and the ones that are an institution OnCo holds (scripts/trial-sites.ts says how a site is
 * matched). A snapshot whose hash differs from the one the trial record carries is skipped, so the file never
 * describes a different reading from the one the page cites; run the fetcher first and then this.
 *
 * Writes src/data/trial-sites.ts.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { graph } from "../src/lib/graph";
import { institutionNames, recruitingSites, type InstitutionNames } from "./trial-sites";

const root = process.cwd();
const cacheArg = process.argv.slice(2).find((a) => a.startsWith("--cache="));
const cache = cacheArg ? cacheArg.slice("--cache=".length) : join(root, ".cache/trial-participation");
const studies = join(cache, "studies");
if (!existsSync(studies)) {
  console.error(`No capture at ${studies}. Run scripts/fetch-trial-participation.ts first, or pass --cache=.`);
  process.exit(1);
}

const g = graph();
const byCountry = new Map<string, InstitutionNames[]>();
for (const i of g.kind("institution")) {
  const n = institutionNames(i);
  const list = byCountry.get(n.country) ?? [];
  list.push(n);
  byCountry.set(n.country, list);
}

type Out = { sha: string; countries: Record<string, Array<[string, number]>>; institutions?: Record<string, string[]> };
const out: Record<string, Out> = {};
let read = 0, missing = 0, stale = 0, unplaced = 0, sites = 0, matched = 0;
const seen = new Set<string>();
for (const t of g.kind("trial")) for (const p of t.participation ?? []) {
  if (seen.has(p.nct)) continue;
  seen.add(p.nct);
  const file = join(studies, `${p.nct}.json`);
  if (!existsSync(file)) { missing++; continue; }
  const snap = JSON.parse(readFileSync(file, "utf8")) as { studySha256: string; study: { protocolSection?: { contactsLocationsModule?: { locations?: Array<{ facility?: string; city?: string; country?: string; status?: string }> } } } };
  if (snap.studySha256 !== p.studySha256) { stale++; continue; }
  read++;
  const s = recruitingSites(snap.study.protocolSection?.contactsLocationsModule?.locations ?? [], byCountry);
  unplaced += s.unplaced;
  if (!Object.keys(s.countries).length) continue;
  sites += Object.values(s.countries).flat().reduce((a, [, n]) => a + n, 0);
  matched += Object.values(s.institutions).reduce((a, l) => a + l.length, 0);
  out[p.nct] = { sha: p.studySha256.slice(0, 16), countries: s.countries, ...(Object.keys(s.institutions).length ? { institutions: s.institutions } : {}) };
}

const ordered = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
const body = `/**
 * GENERATED by scripts/build-trial-sites.ts from the ClinicalTrials.gov capture behind src/data/trial-participation.ts,
 * courtesy of the National Library of Medicine. Do not edit by hand.
 *
 * For each registry id, the sites whose own status is RECRUITING, by country (alpha-2) and city as the registry
 * writes it, and the sites that are an institution OnCo holds, with the names the registry gives them. \`sha\` is
 * the first 16 hex digits of the SHA-256 the trial record carries for the same capture.
 *
 * Studies read ${read}; recruiting sites placed ${sites}, of which ${matched} distinct site names matched an institution;
 * recruiting sites in a country with no code ${unplaced}; snapshots missing ${missing}; snapshots newer than the record ${stale}.
 */
export type TrialSites = { sha: string; countries: Record<string, Array<[string, number]>>; institutions?: Record<string, string[]> };

export const TRIAL_SITES: Record<string, TrialSites> = ${JSON.stringify(ordered)};
`;
writeFileSync(join(root, "src/data/trial-sites.ts"), body);
console.log(JSON.stringify({ studies: Object.keys(ordered).length, read, sites, matched, unplaced, missing, stale, bytes: body.length }));
